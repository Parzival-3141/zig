//! Linker consumes MIR and produces a binary file (link.File)

// codegen.zig calls the backend's CodeGen.generate() via codegen.generateFunction(), which creates the MIR for a function.
// The linker ingests the MIR, at some point lowering the MIR to machine code (Mir.emit() via codegen.emitFunction(), or using custom emit logic e.g. Wasm & C linkers)
// Whether the linker uses custom emission instead of codegen.emitFunction() seems to depend on the linker understanding the backend's MIR directly

// There are two "types" of backends: codegen and linker.
// Linker backends are responsible for constructing the final object binary.
// CodeGen backends are responsible for lowering AIR to MIR (essentially lowering to machine code).
// Linker backends can be loosely or tightly coupled to CodeGen backends, depending on the target.
// For example, the ELF linker emits ELF objects, which may contain code generated by the x86/riscv/etc. backends,
// whereas the C linker emits textual C code files, the text (MIR) of which must be generated by the C CodeGen backend.
// As such, the ELF linker is MIR agnostic, and the C linker directly assembles C MIR (text).

// Linkers that are MIR agnostic can convert MIR to code ready for linking by calling codegen.emitFunction(),
// which in turn calls Mir.emit(), provided that the type of MIR generated supports it.
// Some MIR is only intended to be used by a specific Linker (i.e. C and Wasm).

// Some backends do not follow the template described above. The LLVM and SPIRV backends have no codegen to linker phase,
// and generate objects directly. I think of them as CodeGen backends masquerading as Linker backends. SPIRV is extra weird
// since it shares codepaths with the normal Linkers, unlike LLVM which is handled specially.

// Here's pseudo-code describing the control flow of how backends are driven:
// Compilation.performAllTheWork() -> Compilation.processOneJob(job) {
//     switch (job) {
//         .codegen_func => {
//             // llvm/spirv backends generate objects directly and have no codegen->linker_emit phase.
//             // They are CodeGen backends masquerading as Linker backends. Spirv is extra weird since
//             // it shares codepaths with the normal Linkers, unlike llvm which is handled specially.
//             const codegen_backend_produces_mir = CompilerBackend != (.spirv or .llvm);
//
//             PerThread.runCodegen() -> PerThread.runCodegenInner() ->
//                 if (codegen_backend_produces_mir)
//                     codegen.generateFunction() -> CodeGenBackend.generate() // generates MIR
//                 else
//                     // (note this function is named like the normal version, even though it ingests AIR directly. Confusing!)
//                     SpecialBackend.updateFunc(); // creates object directly from AIR
//
//             Compilation.dispatchZcuLinkTask(.link_func) -> link.doZcuTask(.link_func) ->
//                 if (codegen_backend_produces_mir) // the actual code checks whether MIR has been populated, but it's conceptually the same.
//                     LinkerBackend.updateFunc() // link the generated MIR into the object
//                 else {
//                     // there is no MIR to link
//                 };
//         },
//         .link_nav, .link_type, .update_line_number => |link_job| {
//             Compilation.dispatchZcuLinkTask(link_job) -> link.doZcuTask(link_job) -> switch(link_job) {
//                 .link_nav => LinkerBackend.updateNav(),
//                 .link_func => unreachable, // handled above in codegen_func codepath
//                 .link_type => LinkerBackend.updateContainerType(), // emit typed debug info, only used by elf backend
//                 .update_line_number => LinkerBackend.updateLineNumber(),
//             };
//         },
//     }
// };

